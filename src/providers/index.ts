export class ProviderRegistry {
  private providers: Map<string, IAnimeProvider> = new Map();

  constructor() {
    // Priority order: self-hosted providers first, followed by others
    this.register(marinProvider);
    this.register(animePaheProvider);
    this.register(animeOnsenProvider);
    this.register(animeHeavenProvider);
    this.register(reAnimeProvider);
    this.register(kickAssAnimeProvider);
    this.register(senshiProvider);
    this.register(aniPmProvider);
    this.register(animeParadiseProvider);
    this.register(shiroProvider);
    this.register(animoTvSlashProvider);
    this.register(xAnimeProvider);
    this.register(dhive2Provider);
    this.register(aniWorldProvider);
    this.register(aniKuroProvider);
    this.register(animeLoadsProvider);
    this.register(animeNoSubProvider);
    this.register(kimoiTvProvider);
    this.register(av1Provider);
    this.register(animeyaProvider);
    this.register(animeDunyaProvider);
    this.register(animeGGProvider);
    this.register(anilibriaProvider);
    this.register(animeFlvProvider);
    this.register(animecixProvider);
    this.register(aniChanProvider);

    // Hybrid & third-party providers
    this.register(miruroProvider);
    this.register(allAnimeProvider);
    this.register(anifyProvider);
    this.register(fireAnimeProvider);
    this.register(wcoProvider);
    this.register(anikotoProvider);
    this.register(aniWavesProvider);
    this.register(animeNexusProvider);
    this.register(aniBdProvider);
    this.register(animoProvider);
    this.register(zenkaiProvider);
    this.register(aniNekoProvider);
    this.register(aniHQProvider);
    this.register(aniZoneProvider);
    this.register(mKissaProvider);
    this.register(turkAnimeProvider);
    this.register(jkAnimeProvider);
    this.register(aniziumProvider);
  }

  register(provider: IAnimeProvider): void {
    this.providers.set(provider.name.toLowerCase(), provider);
  }

  getProvider(name: string): IAnimeProvider | undefined {
    return this.providers.get(name.toLowerCase());
  }

  getAllProviders(): IAnimeProvider[] {
    return Array.from(this.providers.values());
  }

  getProviderNames(): string[] {
    return Array.from(this.providers.keys());
  }

  getSelfHostedProviders(): IAnimeProvider[] {
    return Array.from(this.providers.values()).filter((p) => p.isSelfHosted === true);
  }

  getProvidersByLanguage(lang: string): IAnimeProvider[] {
    return Array.from(this.providers.values()).filter((p) => p.languages.includes(lang.toLowerCase()));
  }

  getEverythingMoeIndex(): EverythingMoeSourceInfo[] {
    return Array.from(this.providers.values()).map((p) => ({
      name: p.name,
      baseUrl: p.defaultBaseUrl,
      isSelfHosted: p.isSelfHosted ?? false,
      librarySize: p.librarySize ?? 'Unknown',
      serverType: p.serverType ?? 'third-party',
      languages: p.languages,
      notes: p.notes,
      mediaType: 'anime',
    }));
  }
}

export const providerRegistry = new ProviderRegistry();
